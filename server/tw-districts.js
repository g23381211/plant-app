function normalize(s){ return String(s || "").trim().replace(/\s+/g, ""); }

/**
 * 嘗試把「城市＋行政區」轉成座標。
 * 回傳 { lat, lon, source } 或 null（表示本地表查不到，交給呼叫端做 geocoding fallback）。
 */
function lookupCoords(city, district){
  const c = normalize(city);
  const d = normalize(district);
  if(c && d){
    const key = c + d;
    if(TW_DISTRICTS[key]){
      const [lat, lon] = TW_DISTRICTS[key];
      return { lat, lon, source: "local-district" };
    }
  }
  if(c && TW_CITY_CENTER[c]){
    const [lat, lon] = TW_CITY_CENTER[c];
    return { lat, lon, source: "local-city" };
  }
  return null;
}

